"""Materialize (untracked) verified inputs from the repository's semantic analysis.

No inference, retraining or semantic extraction is performed by this helper.
The annotated CSVs are generated by the frozen semantic scoring workflow.
"""
from pathlib import Path
import hashlib
import json
import shutil

ROOT = Path(__file__).resolve().parents[1]
SEM = ROOT.parent / 'semantic_evaluation' / 'results'
TARGET = ROOT / 'inputs'
EXPECTED = json.loads((ROOT / 'SOURCE_INPUT_SHA256.json').read_text())
REQUIRED = [
    'general_only_fine_tuned_annotated.csv',
    'general_only_zero_shot_annotated.csv',
    'per_property_metrics.csv',
    'paired_protein_bootstrap.csv',
]

def main():
    paths = []
    for name in REQUIRED:
        origin = SEM / name
        if not origin.is_file():
            raise SystemExit(
                f'Missing {origin}\n'
                'Generate missing annotated files using: '
                'python3 analysis/semantic_evaluation/scripts/analyze.py --source .'
            )
        actual = hashlib.sha256(origin.read_bytes()).hexdigest()
        desired = EXPECTED['inputs/' + name]
        if actual != desired:
            raise SystemExit(f'Source hash mismatch for {origin}: expected {desired}, got {actual}')
        paths.append((origin, name))
    TARGET.mkdir(parents=True, exist_ok=True)
    for origin, name in paths:
        shutil.copyfile(origin, TARGET / name)
    print('PASS: 4 archived semantic inputs materialized with exact original SHA-256 hashes.')

if __name__ == '__main__':
    main()
